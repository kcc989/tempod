//! Turns packages/protocol/schema/*.json (Effect's JSON Schema Draft-07 output) into
//! crates/tempo-protocol/src/generated.rs with typify (07, C5).

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use serde_json::{Map, Value, json};
use typify::{TypeSpace, TypeSpaceImpl, TypeSpaceSettings};

/// Types written by hand in tempo-protocol (see spikes/S16.md for why), with the impls typify may rely on.
const HAND_WRITTEN: &[(&str, &[TypeSpaceImpl])] =
    &[("Item", &[]), ("Empty", &[TypeSpaceImpl::Default])];

fn main() {
    let args: Vec<String> = std::env::args().collect();
    if args.len() != 3 {
        eprintln!("usage: protocol-gen <schema dir> <generated.rs>");
        std::process::exit(2);
    }
    if let Err(e) = generate(Path::new(&args[1]), &PathBuf::from(&args[2])) {
        eprintln!("protocol-gen: {e}");
        std::process::exit(1);
    }
}

fn generate(schema_dir: &Path, out: &Path) -> Result<(), String> {
    let (defs, api) = read_schemas(schema_dir)?;

    let mut settings = TypeSpaceSettings::default();
    settings.with_struct_builder(false);
    settings.with_derive("PartialEq".to_string());
    settings.with_map_type("::std::collections::BTreeMap");
    for (name, impls) in HAND_WRITTEN {
        if !defs.contains_key(*name) {
            return Err(format!("hand-written type {name} has no schema"));
        }
        settings.with_replacement(*name, format!("crate::{name}"), impls.iter().cloned());
    }
    let mut space = TypeSpace::new(&settings);
    let schemas = defs
        .iter()
        .map(|(k, v)| {
            serde_json::from_value::<schemars::schema::Schema>(v.clone())
                .map(|s| (k.clone(), s))
                .map_err(|e| format!("{k}: {e}"))
        })
        .collect::<Result<Vec<_>, _>>()?;
    space
        .add_ref_types(schemas)
        .map_err(|e| format!("typify: {e}"))?;
    if space.uses_regress() || space.uses_chrono() || space.uses_uuid() {
        return Err("the generated code needs a crate tempo-protocol does not depend on".into());
    }

    let file: syn::File = syn::parse2(space.to_stream()).map_err(|e| format!("parse: {e}"))?;
    let mut code = String::from(HEADER);
    code.push_str(&prettyplease::unparse(&file));
    code.push_str(&api_table(&api)?);
    code.push_str(&wire_registry(&defs));
    fs::write(out, code).map_err(|e| format!("{}: {e}", out.display()))?;
    let status = Command::new("rustfmt")
        .args(["--edition", "2024"])
        .arg(out)
        .status()
        .map_err(|e| format!("rustfmt: {e}"))?;
    if !status.success() {
        return Err("rustfmt failed".into());
    }
    Ok(())
}

type Defs = BTreeMap<String, Value>;

fn read_schemas(dir: &Path) -> Result<(Defs, Value), String> {
    let mut paths: Vec<PathBuf> = fs::read_dir(dir)
        .map_err(|e| format!("{}: {e}", dir.display()))?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "json"))
        .collect();
    paths.sort();
    let mut defs = Defs::new();
    let mut api = None;
    for path in paths {
        let name = path
            .file_stem()
            .unwrap_or_default()
            .to_string_lossy()
            .into_owned();
        let text = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        let mut value: Value =
            serde_json::from_str(&text).map_err(|e| format!("{}: {e}", path.display()))?;
        if let Value::Object(map) = &mut value {
            map.remove("$schema");
            map.remove("title");
        }
        if name == "Api" {
            api = Some(value);
        } else {
            defs.insert(name, normalize(value));
        }
    }
    Ok((defs, api.ok_or("Api.json is missing")?))
}

const HEADER: &str = "// @generated by crates/protocol-gen from packages/protocol/schema. Do not edit.\n\
// Run `bun run protocol:gen` to regenerate.\n\n";

/// Rewrites Effect's Draft-07 output into equivalent shapes that typify maps to plain Rust types.
fn normalize(value: Value) -> Value {
    match value {
        Value::Array(items) => Value::Array(items.into_iter().map(normalize).collect()),
        Value::Object(map) => normalize_object(map),
        other => other,
    }
}

fn normalize_object(map: Map<String, Value>) -> Value {
    // Effect's Struct({}) is "any value but null"; on the wire it is always `{}`.
    if map.len() == 1 && map.get("not") == Some(&json!({"type": "null"})) {
        return json!({"type": "object", "properties": {}});
    }
    let mut map: Map<String, Value> = map.into_iter().map(|(k, v)| (k, normalize(v))).collect();
    if let Some(Value::String(r)) = map.get("$ref")
        && let Some(name) = r.strip_suffix(".json")
    {
        let target = format!("#/definitions/{name}");
        map.insert("$ref".into(), Value::String(target));
    }
    // `true` is the default; typify only builds tagged enums from objects without it.
    if map.get("additionalProperties") == Some(&Value::Bool(true)) {
        map.remove("additionalProperties");
    }
    if let Some(Value::Array(members)) = map.remove("anyOf") {
        let mut unique: Vec<Value> = Vec::new();
        for m in members {
            let nested = match m {
                Value::Object(mut inner) if inner.len() == 1 && inner.contains_key("anyOf") => {
                    match inner.remove("anyOf") {
                        Some(Value::Array(nested)) => nested,
                        _ => Vec::new(),
                    }
                }
                other => vec![other],
            };
            for n in nested {
                if !unique.contains(&n) {
                    unique.push(n);
                }
            }
        }
        // Schema.Number's JSON codec also accepts "Infinity", "-Infinity" and "NaN"; JSON.stringify never sends them.
        if unique.contains(&json!({"type": "number"})) {
            unique.retain(|m| {
                m != &json!({"type": "string", "enum": ["Infinity", "-Infinity", "NaN"]})
            });
        }
        if unique.contains(&json!({})) {
            return Value::Object(map);
        }
        if unique.len() == 1 && map.is_empty() {
            return unique.pop().unwrap_or_default();
        }
        map.insert("anyOf".into(), Value::Array(unique));
    }
    Value::Object(map)
}

fn pascal(name: &str) -> String {
    let mut chars = name.chars();
    match chars.next() {
        Some(c) => c.to_uppercase().chain(chars).collect(),
        None => String::new(),
    }
}

fn rust_type(fn_name: &str, side: &str, schema: &Value) -> Result<String, String> {
    let named = |v: &Value| {
        v.get("$ref")
            .and_then(Value::as_str)
            .and_then(|r| r.strip_suffix(".json"))
            .map(|n| format!("crate::{n}"))
    };
    if let Some(t) = named(schema) {
        return Ok(t);
    }
    if schema.get("type") == Some(&json!("array"))
        && let Some(t) = schema.get("items").and_then(named)
    {
        return Ok(format!("::std::vec::Vec<{t}>"));
    }
    Err(format!(
        "Api.json: {fn_name}.{side} is neither a reference nor an array of one"
    ))
}

fn api_table(api: &Value) -> Result<String, String> {
    let functions = api
        .get("properties")
        .and_then(Value::as_object)
        .ok_or("Api.json has no properties")?;
    let mut out = String::from(
        "\n/// One marker type per server function (02), callable at `POST /api/v1/rpc/<NAME>`.\npub mod api {\n",
    );
    let mut all = String::new();
    for (name, f) in functions {
        let props = f
            .get("properties")
            .ok_or(format!("Api.json: {name} has no properties"))?;
        let method = match props.pointer("/method/const").and_then(Value::as_str) {
            Some("GET") => "Get",
            Some("POST") => "Post",
            other => return Err(format!("Api.json: {name} has method {other:?}")),
        };
        let input = rust_type(name, "input", props.get("input").unwrap_or(&Value::Null))?;
        let output = rust_type(name, "output", props.get("output").unwrap_or(&Value::Null))?;
        let marker = pascal(name);
        let _ = write!(
            out,
            "    /// `{name}`\n    #[derive(Clone, Copy, Debug)]\n    pub struct {marker};\n    \
             impl crate::Function for {marker} {{\n        const NAME: &'static str = \"{name}\";\n        \
             const METHOD: crate::Method = crate::Method::{method};\n        type Input = {input};\n        \
             type Output = {output};\n    }}\n"
        );
        let _ = writeln!(all, "        (\"{name}\", crate::Method::{method}),");
    }
    let _ = write!(
        out,
        "    /// Every function name with the HTTP method of its web wrapper.\n    \
         pub const ALL: &[(&str, crate::Method)] = &[\n{all}    ];\n}}\n"
    );
    Ok(out)
}

fn wire_registry(defs: &Defs) -> String {
    let mut names = String::new();
    let mut arms = String::new();
    for name in defs.keys() {
        let _ = writeln!(names, "        \"{name}\",");
        let _ = writeln!(
            arms,
            "            \"{name}\" => crate::roundtrip::<crate::{name}>(text),"
        );
    }
    format!(
        "\n/// Every wire type by its schema name, for the fixture tests.\n#[doc(hidden)]\npub mod wire {{\n    \
         pub const NAMES: &[&str] = &[\n{names}    ];\n\n    \
         /// Decodes `text` as the named type and returns it encoded again; None for an unknown name.\n    \
         pub fn roundtrip(name: &str, text: &str) -> Option<Result<::serde_json::Value, ::std::string::String>> {{\n        \
         Some(match name {{\n{arms}            _ => return None,\n        }})\n    }}\n}}\n"
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn numbers_drop_the_non_finite_strings() {
        let effect = json!({"anyOf": [{"type": "number"}, {"type": "string", "enum": ["Infinity", "-Infinity", "NaN"]}]});
        assert_eq!(normalize(effect), json!({"type": "number"}));
    }

    #[test]
    fn nested_nullable_unions_flatten() {
        let effect = json!({"anyOf": [{"anyOf": [{"$ref": "Turn.json"}, {"type": "null"}]}, {"type": "null"}]});
        assert_eq!(
            normalize(effect),
            json!({"anyOf": [{"$ref": "#/definitions/Turn"}, {"type": "null"}]})
        );
    }

    #[test]
    fn unknown_absorbs_its_union() {
        assert_eq!(
            normalize(json!({"anyOf": [{}, {"type": "null"}]})),
            json!({})
        );
    }

    #[test]
    fn open_objects_and_empty_structs() {
        let effect = json!({"type": "object", "properties": {"a": {"not": {"type": "null"}}}, "additionalProperties": true});
        assert_eq!(
            normalize(effect),
            json!({"type": "object", "properties": {"a": {"type": "object", "properties": {}}}})
        );
        let record = json!({"type": "object", "additionalProperties": {"type": "string"}});
        assert_eq!(normalize(record.clone()), record);
    }

    #[test]
    fn api_types_are_references_or_arrays_of_them() {
        assert_eq!(
            rust_type("f", "input", &json!({"$ref": "Empty.json"})).unwrap(),
            "crate::Empty"
        );
        assert_eq!(
            rust_type(
                "f",
                "output",
                &json!({"type": "array", "items": {"$ref": "Project.json"}})
            )
            .unwrap(),
            "::std::vec::Vec<crate::Project>"
        );
        assert!(rust_type("f", "output", &json!({"type": "string"})).is_err());
    }

    #[test]
    fn pascal_case_function_names() {
        assert_eq!(pascal("sendPrompt"), "SendPrompt");
    }
}
